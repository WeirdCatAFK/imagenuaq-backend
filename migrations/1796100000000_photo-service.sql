-- Servicio de fotografía (RF-PRY-06; primera sesión, servicio de fotos de graduación).
--
-- Un grupo ("Bachiller grupo 7 2026-1") nace con un tamaño y la base guarda desde ese momento un
-- folio por lugar, cada uno con un código de 8 caracteres que es la credencial de quien lo recibe:
-- no hay cuenta de cliente. Del código solo se busca el hash; el cifrado sirve para reimprimir la
-- hoja. El catálogo de paquetes y los días que viven las fotos se configuran sin desplegar, y el
-- folio copia nombre, cantidades y monto al cobrarse, así que cambiar un precio no reescribe lo
-- que ya se pagó. Los bytes viven en un bucket aparte del de documentos (DATAMODEL §2.23).

