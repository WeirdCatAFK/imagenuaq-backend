-- El evento nace con el grupo y lo sigue, como el de una reserva de vehículo.
CREATE FUNCTION photo_groups_create_event() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO events (event_type_id, title, starts_at, ends_at, created_by)
    SELECT et.id, 'Fotografía: ' || NEW.name, NEW.event_starts_at, NEW.event_ends_at, NEW.created_by
      FROM event_types et
     WHERE et.code = 'fotografia'
    RETURNING id INTO NEW.event_id;
    RETURN NEW;
END;
$$;

CREATE TRIGGER photo_groups_create_event
    BEFORE INSERT ON photo_groups
    FOR EACH ROW
    EXECUTE FUNCTION photo_groups_create_event();

CREATE FUNCTION photo_groups_sync_event() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        DELETE FROM events WHERE id = OLD.event_id;
        RETURN NULL;
    END IF;
    UPDATE events
       SET title = 'Fotografía: ' || NEW.name, starts_at = NEW.event_starts_at, ends_at = NEW.event_ends_at
     WHERE id = NEW.event_id;
    RETURN NULL;
END;
$$;

CREATE TRIGGER photo_groups_sync_event
    AFTER UPDATE OF name, event_starts_at, event_ends_at OR DELETE ON photo_groups
    FOR EACH ROW
    EXECUTE FUNCTION photo_groups_sync_event();

