CREATE TABLE photo_packages (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(100) NOT NULL UNIQUE,
    description   text,
    digital_count integer NOT NULL,
    print_count   integer NOT NULL DEFAULT 0,
    price         numeric(12, 2) NOT NULL,
    presale_price numeric(12, 2),
    is_active     boolean NOT NULL DEFAULT true,
    CONSTRAINT photo_packages_counts CHECK (digital_count > 0 AND print_count >= 0),
    CONSTRAINT photo_packages_prices CHECK (price >= 0 AND (presale_price IS NULL OR presale_price >= 0))
);

COMMENT ON TABLE photo_packages IS 'Catálogo de precios del servicio de fotografía. Se retira con is_active = false, nunca se borra.';
COMMENT ON COLUMN photo_packages.presale_price IS 'Precio antes del presale_until del grupo. NULL = sin precio de preventa.';

CREATE TABLE photo_groups (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            varchar(200) NOT NULL,
    code            varchar(12) NOT NULL UNIQUE,
    event_id        bigint UNIQUE REFERENCES events (id) ON DELETE SET NULL,
    event_starts_at timestamptz NOT NULL,
    event_ends_at   timestamptz NOT NULL,
    presale_until   timestamptz,
    download_days   integer NOT NULL,
    notes           text,
    created_by      bigint NOT NULL REFERENCES users (id),
    created_at      timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at       timestamptz,
    CONSTRAINT photo_groups_code_shape CHECK (code ~ '^[A-Z0-9]{1,12}$'),
    CONSTRAINT photo_groups_range CHECK (event_ends_at > event_starts_at),
    CONSTRAINT photo_groups_days_positive CHECK (download_days > 0)
);

COMMENT ON TABLE photo_groups IS 'Un grupo de la sesión de fotos. code es el prefijo con que se leen sus folios (B7-001).';

CREATE TABLE photo_group_packages (
    group_id   bigint NOT NULL REFERENCES photo_groups (id) ON DELETE CASCADE,
    package_id bigint NOT NULL REFERENCES photo_packages (id),
    PRIMARY KEY (group_id, package_id)
