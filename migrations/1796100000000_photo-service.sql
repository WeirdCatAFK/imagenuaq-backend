CREATE TABLE photo_retention (
    id         boolean PRIMARY KEY DEFAULT true,
    days       integer NOT NULL DEFAULT 30,
    updated_by bigint REFERENCES users (id) ON DELETE SET NULL,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT photo_retention_single_row CHECK (id),
    CONSTRAINT photo_retention_days_positive CHECK (days > 0)
);

COMMENT ON TABLE photo_retention IS 'Una fila: cuántos días puede descargar sus fotos un folio desde que quedan listas. Lo copia cada grupo nuevo.';

