-- El calendario (`RF-CAL-02`, `RF-CAL-03`, `RF-CAL-05`): todo lo que ocupa tiempo ya vive en
-- `events`; aquí se le da de qué llenarse.
--
-- Una etapa aparece en el calendario como un evento propio desde que se activa hasta la fecha
-- de entrega de su proyecto, con su área y su responsable como participantes. Lo mantiene un
-- disparador sobre `project_stages` porque las etapas se crean y avanzan desde varios caminos
-- (convertir una solicitud, agregar etapa, avanzar, repetir tras un rechazo) y ninguno debe
-- olvidarlo. Un evento sin participantes es global: lo ven todos.
--
-- La ventana administrativa de cierre de semestre es una tabla aparte: no se solapa consigo
-- misma y solo marca los proyectos con costo que caen en ella, no los bloquea.
--
-- `calendar_occurrences` expande la recurrencia al leer. Solo entiende `FREQ=YEARLY` y
-- `FREQ=WEEKLY;BYDAY=…`, con el fin en `recurrence_until`; la API rechaza cualquier otra regla.

