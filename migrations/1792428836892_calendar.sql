-- El evento de una etapa: se crea al activarse, cambia de participante al reasignarse y se
-- cierra al terminar. Una etapa que ya terminó sin tenerlo (las anteriores al calendario) lo
-- recibe de su inicio a su fin. Los días completos guardan el fin como la medianoche siguiente.
CREATE FUNCTION project_stages_sync_event() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    stage      record;
    zone       text := 'America/Mexico_City';
    first_day  date;
    last_day   date;
    collection bigint;
    created    bigint;
BEGIN
    IF NEW.event_id IS NOT NULL THEN
        IF TG_OP = 'UPDATE' AND NEW.assigned_to IS DISTINCT FROM OLD.assigned_to THEN
            DELETE FROM event_participants WHERE event_id = NEW.event_id AND user_id IS NOT NULL;
            IF NEW.assigned_to IS NOT NULL THEN
                INSERT INTO event_participants (event_id, user_id) VALUES (NEW.event_id, NEW.assigned_to);
            END IF;
        END IF;
        IF NEW.status IN ('done', 'cancelled') THEN
            UPDATE events
               SET ends_at = greatest(starts_at + interval '1 day',
                                      (((coalesce(NEW.ended_at, now()) AT TIME ZONE timezone)::date + 1)::timestamp
                                       AT TIME ZONE timezone))
             WHERE id = NEW.event_id;
        END IF;
        RETURN NULL;
    END IF;

    IF NEW.status = 'pending' OR (NEW.status IN ('done', 'cancelled') AND NEW.started_at IS NULL) THEN
        RETURN NULL;
    END IF;

    SELECT fs.area_id, fs.title, p.id AS project_id, p.key, p.title AS project_title, p.due_on,
           p.event_collection_id
      INTO stage
      FROM flow_stages fs
      JOIN flow_phases fp ON fp.id = fs.phase_id
      JOIN projects p ON p.id = fp.project_id
     WHERE fs.id = NEW.flow_stage_id;
    IF NOT FOUND THEN
        RETURN NULL;
    END IF;

    collection := stage.event_collection_id;
    IF collection IS NULL THEN
        INSERT INTO event_collections (key, name)
        VALUES ('proyecto_' || stage.project_id, stage.key || ' · ' || stage.project_title)
        ON CONFLICT (key) DO UPDATE SET name = excluded.name
        RETURNING id INTO collection;
        UPDATE projects SET event_collection_id = collection WHERE id = stage.project_id;
    END IF;

    first_day := (coalesce(NEW.started_at, now()) AT TIME ZONE zone)::date;
    last_day := CASE
                    WHEN NEW.status IN ('done', 'cancelled')
                        THEN (coalesce(NEW.ended_at, now()) AT TIME ZONE zone)::date
                    ELSE coalesce(stage.due_on, first_day)
                END;
    INSERT INTO events (event_type_id, title, all_day, starts_at, ends_at, timezone)
    SELECT et.id, stage.key || ' · ' || stage.title, true,
           first_day::timestamp AT TIME ZONE zone,
           (greatest(last_day, first_day) + 1)::timestamp AT TIME ZONE zone,
           zone
      FROM event_types et
     WHERE et.code = 'proyecto'
    RETURNING id INTO created;

    INSERT INTO event_participants (event_id, area_id) VALUES (created, stage.area_id);
    IF NEW.assigned_to IS NOT NULL THEN
        INSERT INTO event_participants (event_id, user_id) VALUES (created, NEW.assigned_to);
    END IF;
    INSERT INTO collection_events (event_id, collection_id) VALUES (created, collection);
    UPDATE project_stages SET event_id = created WHERE id = NEW.id;
    RETURN NULL;
END;
$$;

CREATE TRIGGER project_stages_sync_event
    AFTER INSERT OR UPDATE OF status, assigned_to, ended_at ON project_stages
    FOR EACH ROW
    EXECUTE FUNCTION project_stages_sync_event();

-- Mover la fecha de entrega del proyecto mueve el fin de sus etapas abiertas.
CREATE FUNCTION projects_sync_stage_events() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    UPDATE events e
       SET ends_at = (greatest(coalesce(NEW.due_on, (e.starts_at AT TIME ZONE e.timezone)::date),
                               (e.starts_at AT TIME ZONE e.timezone)::date) + 1)::timestamp
                     AT TIME ZONE e.timezone
      FROM project_stages ps
      JOIN flow_stages fs ON fs.id = ps.flow_stage_id
      JOIN flow_phases fp ON fp.id = fs.phase_id
     WHERE ps.event_id = e.id
       AND fp.project_id = NEW.id
       AND ps.status IN ('pending', 'active', 'waiting_external');
    RETURN NULL;
END;
$$;

CREATE TRIGGER projects_sync_stage_events
    AFTER UPDATE OF due_on ON projects
    FOR EACH ROW
    WHEN (OLD.due_on IS DISTINCT FROM NEW.due_on)
    EXECUTE FUNCTION projects_sync_stage_events();

-- Cada ocurrencia de cada evento que toca la ventana [p_from, p_to). Una ocurrencia movida
-- desde fuera de la ventana hacia dentro no aparece: se busca por su inicio original.
CREATE FUNCTION calendar_occurrences(p_from timestamptz, p_to timestamptz)
RETURNS TABLE (event_id bigint, starts_at timestamptz, ends_at timestamptz)
LANGUAGE sql STABLE AS $$
    WITH base AS (
        SELECT e.id, e.starts_at, e.ends_at - e.starts_at AS span, e.timezone, e.recurrence_until,
               e.starts_at AT TIME ZONE e.timezone AS local_start,
               substring(e.rule FROM 'FREQ=([A-Z]+)') AS freq,
               string_to_array(substring(e.rule FROM 'BYDAY=([A-Z,]+)'), ',') AS byday
          FROM events e
         WHERE e.starts_at < p_to
           AND (e.rule IS NULL AND e.ends_at > p_from
                OR e.rule IS NOT NULL AND (e.recurrence_until IS NULL OR e.recurrence_until >= p_from - (e.ends_at - e.starts_at)))
    ),
    raw AS (
        SELECT id, starts_at AS original, span FROM base WHERE freq IS NULL
        UNION ALL
        SELECT b.id, (b.local_start + make_interval(years => n)) AT TIME ZONE b.timezone, b.span
          FROM base b,
               generate_series(
                   greatest(0, extract(year FROM (p_from - b.span) AT TIME ZONE b.timezone)::int
                               - extract(year FROM b.local_start)::int - 1),
                   extract(year FROM p_to AT TIME ZONE b.timezone)::int - extract(year FROM b.local_start)::int
               ) AS n
         WHERE b.freq = 'YEARLY'
        UNION ALL
        SELECT b.id, (d::date + b.local_start::time) AT TIME ZONE b.timezone, b.span
          FROM base b,
               generate_series(
                   greatest(b.local_start::date, ((p_from - b.span) AT TIME ZONE b.timezone)::date),
                   (p_to AT TIME ZONE b.timezone)::date,
                   interval '1 day'
               ) AS d
         WHERE b.freq = 'WEEKLY'
           AND (ARRAY['MO', 'TU', 'WE', 'TH', 'FR', 'SA', 'SU'])[extract(isodow FROM d)::int]
               = ANY (coalesce(b.byday,
                               ARRAY[(ARRAY['MO', 'TU', 'WE', 'TH', 'FR', 'SA', 'SU'])[extract(isodow FROM b.local_start)::int]]))
    )
    SELECT r.id, coalesce(x.starts_at, r.original), coalesce(x.ends_at, r.original + r.span)
      FROM raw r
      JOIN base b ON b.id = r.id
      LEFT JOIN event_exceptions x ON x.event_id = r.id AND x.original_start = r.original
     WHERE r.original >= b.starts_at
       AND (b.recurrence_until IS NULL OR r.original <= b.recurrence_until)
       AND r.original < p_to
       AND r.original + r.span > p_from
       AND NOT coalesce(x.is_cancelled, false)
$$;

