-- Reservas de vehículo para entregar y recoger material (`RF-CAL-04`: el calendario muestra la
-- disponibilidad de los recursos compartidos para evitar empalmes de reserva).
--
-- Los vehículos son un catálogo que coordinación administra sin despliegue. Una reserva ocupa un
-- vehículo de un instante a otro y no se empalma con otra del mismo vehículo: lo garantiza la
-- base, no la API. Cada reserva tiene su evento en el calendario, global (sin participantes)
-- porque la disponibilidad es de todos; lo mantienen los disparadores, como el de las etapas.

