CREATE TABLE vehicles (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      varchar(100) NOT NULL UNIQUE,
    plate     varchar(20),
    is_active boolean NOT NULL DEFAULT true
);

COMMENT ON TABLE vehicles IS 'RF-CAL-04: los vehículos que se reservan para entregar y recoger material.';

CREATE TABLE vehicle_bookings (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id  bigint NOT NULL REFERENCES vehicles (id),
    event_id    bigint UNIQUE REFERENCES events (id) ON DELETE CASCADE,
    kind        varchar(20) NOT NULL CHECK (kind IN ('delivery', 'pickup')),
    destination varchar(300) NOT NULL,
    project_id  bigint REFERENCES projects (id) ON DELETE SET NULL,
    notes       text,
    starts_at   timestamptz NOT NULL,
    ends_at     timestamptz NOT NULL,
    booked_by   bigint NOT NULL REFERENCES users (id),
    created_at  timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT vehicle_bookings_range CHECK (ends_at > starts_at),
    CONSTRAINT vehicle_bookings_no_overlap
        EXCLUDE USING gist (vehicle_id WITH =, tstzrange(starts_at, ends_at) WITH &&)
);

CREATE INDEX vehicle_bookings_idx_starts_at ON vehicle_bookings (starts_at);

COMMENT ON TABLE vehicle_bookings IS 'RF-CAL-04: un vehículo ocupado de starts_at a ends_at; dos reservas del mismo vehículo no se empalman.';

INSERT INTO event_types (code, label) VALUES ('vehiculo', 'Reserva de vehículo')
ON CONFLICT (code) DO NOTHING;

-- El evento nace con la reserva y la sigue: mismas fechas, mismo destino, se borra con ella.
CREATE FUNCTION vehicle_bookings_create_event() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO events (event_type_id, title, starts_at, ends_at, created_by)
    SELECT et.id, NEW.destination, NEW.starts_at, NEW.ends_at, NEW.booked_by
      FROM event_types et
     WHERE et.code = 'vehiculo'
    RETURNING id INTO NEW.event_id;
    RETURN NEW;
END;
$$;

CREATE TRIGGER vehicle_bookings_create_event
    BEFORE INSERT ON vehicle_bookings
    FOR EACH ROW
    EXECUTE FUNCTION vehicle_bookings_create_event();

CREATE FUNCTION vehicle_bookings_sync_event() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        DELETE FROM events WHERE id = OLD.event_id;
        RETURN NULL;
    END IF;
    UPDATE events
       SET title = NEW.destination, starts_at = NEW.starts_at, ends_at = NEW.ends_at
     WHERE id = NEW.event_id;
    RETURN NULL;
END;
$$;

CREATE TRIGGER vehicle_bookings_sync_event
    AFTER UPDATE OF destination, starts_at, ends_at OR DELETE ON vehicle_bookings
    FOR EACH ROW
    EXECUTE FUNCTION vehicle_bookings_sync_event();

